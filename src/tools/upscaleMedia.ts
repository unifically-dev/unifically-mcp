import type { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { z } from "zod";

import { toolError } from "../errors.js";
import { resolveMediaRef } from "../media.js";
import { callbackUrl, confirmCost, providerOptions, wait } from "../schemas.js";
import { providerOptionsClash, runGeneration, type ToolResult } from "./_helpers.js";

const inputShape = {
  image_url: z
    .string()
    .min(1)
    .optional()
    .describe("Image to upscale (public https URL) — routed to Topaz image upscale, works on any image."),
  video_url: z
    .string()
    .min(1)
    .optional()
    .describe("Video to upscale (public https URL) — routed to Topaz video upscale, works on any video."),
  task_id: z
    .string()
    .min(1)
    .optional()
    .describe("task_id of a completed generation, for the model-internal upscalers. Requires model 'veo-upscale' (Veo generations) or 'grok-upscale' (Grok Imagine generations)."),
  model: z
    .string()
    .optional()
    .describe(
      "Only with task_id: 'veo-upscale' or 'grok-upscale' (full ids accepted too). Omit for URL inputs (Topaz is used). " +
        "'grok-upscale' only works on a task_id from xai/grok-imagine-video — NOT from xai/grok-imagine-1.5-video. For anything else, pass the finished video's URL and let Topaz do it.",
    ),
  resolution: z
    .string()
    .optional()
    .describe(
      "VIDEO target size, e.g. '1080p' or '4k' (defaults to '4k' when omitted). Allowed values differ between Topaz video and veo-upscale. For IMAGE upscaling use upscale_factor instead.",
    ),
  upscale_factor: z
    .string()
    .optional()
    .describe("IMAGE upscale factor for image_url, e.g. '2x'. This is a multiplier, not an output size — distinct from generate_image's resolution."),
  wait,
  callback_url: callbackUrl,
  confirm_cost: confirmCost,
  provider_options: providerOptions,
};

const inputSchema = z.object(inputShape).strict();

// Deliberately NOT an allowlist of each upscaler's resolutions: those change,
// and a stale copy here would reject a size the provider has since added. A bad
// resolution costs a free provider 400. This set exists only to tell a FACTOR
// from a SIZE (below), which is a spend guard, not a validity claim.
const IMAGE_FACTORS = new Set(["2x", "4x", "2", "4"]);

// Accept aliases and full ids for the model-internal upscalers; Topaz
// spellings normalize to undefined (Topaz is the URL-routed default).
function normalizeUpscaler(model: string | undefined): "veo" | "grok" | "topaz" | "unknown" {
  if (!model) return "topaz";
  const m = model.trim().toLowerCase();
  if (m === "veo-upscale" || m === "google/veo-3.1-upscale") return "veo";
  if (m === "grok-upscale" || m === "xai/grok-imagine-upscale") return "grok";
  if (m === "topaz" || m === "upscale" || m === "image-upscale" || m === "video-upscale" || m === "image-generative" || m.startsWith("topaz-labs/")) return "topaz";
  return "unknown";
}

// Topaz image upscale speaks upscale_factor ('2x'/'4x'). A bare '2'/'4' is a
// factor; '2k'/'4k' are absolute sizes and are NOT reinterpreted as factors
// (that would silently produce a far larger, costlier image).
function toUpscaleFactor(value: string): string {
  const v = value.trim().toLowerCase();
  if (v === "2") return "2x";
  if (v === "4") return "4x";
  return v;
}

export function registerUpscaleMedia(server: McpServer): void {
  server.registerTool(
    "upscale_media",
    {
      title: "Upscale media",
      description:
        "Upscale an image or a video. Pass exactly one source: image_url (Topaz image upscale — any image; multiplier via upscale_factor, preset/face_enhancement via provider_options), " +
        "video_url (Topaz video upscale — any video; target size via resolution; preset/target_fps/frame_interpolation via provider_options), " +
        "or task_id with model 'veo-upscale' / 'grok-upscale' (model-internal upscalers that ONLY work on their own model's completed generations). " +
        "For any media not generated by Veo/Grok, use the URL inputs — Topaz works on everything.",
      inputSchema: inputSchema,
      annotations: {
        title: "Upscale media",
        // Irreversible spend — see generate_video for the reasoning.
        readOnlyHint: false,
        destructiveHint: true,
        idempotentHint: false,
        openWorldHint: true,
      },
    },
    async (rawArgs): Promise<ToolResult> => {
      const args = inputSchema.parse(rawArgs);

      const fail = (text: string): ToolResult => ({
        isError: true as const,
        content: [{ type: "text" as const, text }],
      });

      const sources = [args.image_url, args.video_url, args.task_id].filter((v) => v !== undefined);
      if (sources.length !== 1) {
        return fail("Pass exactly one of: image_url (Topaz image), video_url (Topaz video), or task_id (with model 'veo-upscale' / 'grok-upscale').");
      }

      const which = normalizeUpscaler(args.model);
      if (which === "unknown") {
        return fail(`Unknown upscaler '${args.model}'. Use 'veo-upscale' or 'grok-upscale' with task_id, or omit model for Topaz (URL inputs).`);
      }

      if (args.task_id !== undefined) {
        if (which === "topaz") {
          return fail("task_id upscaling is model-internal — set model to 'veo-upscale' (for Veo generations) or 'grok-upscale' (for Grok Imagine generations). For any other media, pass image_url or video_url instead (Topaz works on everything).");
        }
        // veo-upscale REQUIRES a resolution, so one has to be defaulted here;
        // whether the value is allowed is the provider's call, not ours.
        const input: Record<string, unknown> =
          which === "veo"
            ? { task_id: args.task_id, resolution: (args.resolution ?? "4k").trim().toLowerCase() }
            : { task_id: args.task_id };
        const clash = providerOptionsClash(input, args.provider_options);
        if (clash) return clash;
        Object.assign(input, args.provider_options ?? {});
        return runGeneration({
          kind: "upscale",
          model: which === "veo" ? "google/veo-3.1-upscale" : "xai/grok-imagine-upscale",
          input,
          callback_url: args.callback_url,
          confirm_cost: args.confirm_cost,
          wait: args.wait,
        });
      }

      if (which !== "topaz") {
        return fail(`model '${args.model}' only works with task_id of its own model's generation. For URL inputs, omit model — Topaz is used automatically.`);
      }

      if (args.image_url !== undefined) {
        let imageUrl: string;
        try {
          imageUrl = await resolveMediaRef(args.image_url);
        } catch (err) {
          return toolError(err);
        }
        // Prefer the explicit upscale_factor; tolerate resolution as a synonym
        // for agents that reused the video param.
        const rawFactor = args.upscale_factor ?? args.resolution;
        let factor: string | undefined;
        if (rawFactor !== undefined) {
          factor = toUpscaleFactor(rawFactor);
          if (!IMAGE_FACTORS.has(rawFactor.trim().toLowerCase()) && !/^[0-9.]+x?$/i.test(factor)) {
            return fail(`Image upscale takes a factor in upscale_factor: '2x' or '4x' — got '${rawFactor}'.`);
          }
        }
        const input: Record<string, unknown> = {
          image_url: imageUrl,
          ...(factor !== undefined ? { upscale_factor: factor } : {}),
        };
        const clash = providerOptionsClash(input, args.provider_options);
        if (clash) return clash;
        Object.assign(input, args.provider_options ?? {});
        // Honor an explicit request for the generative upscaler instead of
        // silently collapsing every topaz image request to plain upscale.
        const imageModel = /image-generative|generative/.test((args.model ?? "").toLowerCase())
          ? "topaz-labs/image-generative"
          : "topaz-labs/image-upscale";
        return runGeneration({
          kind: "upscale",
          model: imageModel,
          input,
          callback_url: args.callback_url,
          confirm_cost: args.confirm_cost,
          wait: args.wait,
        });
      }

      let videoUrl: string;
      try {
        videoUrl = await resolveMediaRef(args.video_url!);
      } catch (err) {
        return toolError(err);
      }
      const resolution = (args.resolution ?? "4k").trim().toLowerCase();
      const input: Record<string, unknown> = {
        video_url: videoUrl,
        resolution,
      };
      const clash = providerOptionsClash(input, args.provider_options);
      if (clash) return clash;
      Object.assign(input, args.provider_options ?? {});
      return runGeneration({
        kind: "upscale",
        model: "topaz-labs/video-upscale",
        input,
        callback_url: args.callback_url,
        confirm_cost: args.confirm_cost,
        wait: args.wait,
      });
    },
  );
}
